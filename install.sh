#!/bin/sh
# custom-git-hooks installer.
#
# Copies the hooks into <repository>/.githooks (so they can be committed and
# shared with the team) and points `core.hooksPath` at that directory.
#
# Run it from the repository you want to set up, or pass the repository:
#
#   sh /path/to/custom-git-hooks/install.sh [options] [repository]

set -eu

SRC=$(cd "$(dirname "$0")" && pwd -P)
PAYLOAD="$SRC/payload"
VERSION=$(cat "$SRC/VERSION.md" 2>/dev/null || echo unknown)

STUB_MARK='custom-git-hooks stub'

die() {
    echo "install.sh: $*" >&2
    exit 1
}

usage() {
    cat <<EOF
Usage: sh install.sh [options] [repository]

Installs (or updates) custom-git-hooks $VERSION into <repository>/.githooks
(default: the repository of the current directory) and sets core.hooksPath.

Options:
  -d, --dir NAME     hooks directory inside the repository (default: .githooks)
  -n, --dry-run      only print what would be done
  -u, --uninstall    remove the installed files and unset core.hooksPath
  -f, --force        take over a different core.hooksPath / existing hook files
  -h, --help         this help

Your own configuration (cgh.conf) and your own hooks in hooks.d/ are never
overwritten or removed.
EOF
}

dry=0
uninstall=0
force=0
dest_name=.githooks
target=.

while [ $# -gt 0 ]; do
    case $1 in
        -n | --dry-run) dry=1 ;;
        -u | --uninstall) uninstall=1 ;;
        -f | --force) force=1 ;;
        -d | --dir)
            [ $# -gt 1 ] || die "$1 needs a value"
            shift
            dest_name=$1
            ;;
        -h | --help)
            usage
            exit 0
            ;;
        -*) die "unknown option: $1 (see --help)" ;;
        *) target=$1 ;;
    esac
    shift
done

case $dest_name in
    /* | *..* | '') die "--dir has to be a relative path inside the repository" ;;
esac

root=$(git -C "$target" rev-parse --show-toplevel 2>/dev/null) ||
    die "$target is not inside a git repository"
dest="$root/$dest_name"
manifest="$dest/.cgh-manifest"

# act CMD...: run CMD, or only print it with --dry-run
act() {
    if [ "$dry" = 1 ]; then
        printf '  [dry-run] %s\n' "$*"
    else
        "$@"
    fi
}

write_stub() {
    if [ "$dry" = 1 ]; then
        printf '  [dry-run] write stub %s\n' "$1"
        return 0
    fi
    # shellcheck disable=SC2016 # the $(...) belongs to the generated stub
    printf '%s\n' \
        '#!/bin/sh' \
        "# $STUB_MARK (generated by install.sh) - do not edit" \
        'exec "$(dirname "$0")/_dispatch" "$(basename "$0")" "$@"' >"$1"
    chmod +x "$1"
}

is_stub() {
    [ -f "$1" ] && grep -q "$STUB_MARK" "$1"
}

# files managed by the installer: payload files except the seed configuration
payload_files() {
    (cd "$PAYLOAD" && find . -type f ! -name cgh.conf | sed 's|^\./||' | LC_ALL=C sort)
}

# Names of all hooks that need a stub: those with a hooks.d/<hook> directory
# (ours or the user's) and those that already exist as a plain hook in
# .git/hooks, which must keep running once core.hooksPath points elsewhere.
hook_names() {
    seen=' '
    common=$(cd "$root" && cd "$(git rev-parse --git-common-dir)" && pwd -P)
    for d in "$PAYLOAD"/hooks.d/* "$dest"/hooks.d/*; do
        [ -d "$d" ] || continue
        n=$(basename "$d")
        case $seen in *" $n "*) continue ;; esac
        seen="$seen$n "
        printf '%s\n' "$n"
    done
    for h in "$common"/hooks/*; do
        [ -f "$h" ] && [ -x "$h" ] || continue
        n=$(basename "$h")
        case $n in *.sample) continue ;; esac
        grep -q 'CUSTOM-GIT-HOOK-SKELETON' "$h" && continue
        case $seen in *" $n "*) continue ;; esac
        seen="$seen$n "
        printf '%s\n' "$n"
    done
}

old_manifest_files() {
    [ -f "$manifest" ] && sed -n '/^version=/!p' "$manifest"
    return 0
}

do_uninstall() {
    [ -f "$manifest" ] || die "nothing to uninstall: $manifest does not exist"
    echo "Uninstalling custom-git-hooks from $dest"
    old_manifest_files | while IFS= read -r f; do
        if [ -n "$f" ] && [ -e "$dest/$f" ]; then
            act rm -f "$dest/$f"
        fi
    done
    act rm -f "$manifest"
    for d in "$dest"/hooks.d/*; do
        if [ -d "$d" ]; then
            act rmdir "$d" 2>/dev/null || true
        fi
    done
    act rmdir "$dest/hooks.d" 2>/dev/null || true
    act rmdir "$dest" 2>/dev/null || true
    cur=$(git -C "$root" config --local --get core.hooksPath || true)
    if [ "$cur" = "$dest_name" ]; then
        act git -C "$root" config --local --unset core.hooksPath
    fi
    echo "Done. Your cgh.conf and your own hooks (if any) were left in place."
}

do_install() {
    cur=$(git -C "$root" config --local --get core.hooksPath || true)
    if [ -n "$cur" ] && [ "$cur" != "$dest_name" ] && [ "$force" != 1 ]; then
        die "core.hooksPath is already set to '$cur'. Use --force to replace it, or --dir '$cur' to install there."
    fi

    echo "Installing custom-git-hooks $VERSION into $dest"

    new_list=$(payload_files)

    # files of an older installation that no longer exist
    old_manifest_files | while IFS= read -r f; do
        [ -n "$f" ] || continue
        if ! printf '%s\n' "$new_list" | grep -qxF -- "$f" && [ -e "$dest/$f" ]; then
            echo "Remove outdated $dest_name/$f"
            act rm -f "$dest/$f"
        fi
    done

    printf '%s\n' "$new_list" | while IFS= read -r f; do
        [ -n "$f" ] || continue
        act mkdir -p "$(dirname "$dest/$f")"
        act cp "$PAYLOAD/$f" "$dest/$f"
        case $f in
            _dispatch | cgh-check | hooks.d/*) act chmod +x "$dest/$f" ;;
        esac
    done

    if [ -e "$dest/cgh.conf" ]; then
        echo "Keep your existing $dest_name/cgh.conf"
    else
        act mkdir -p "$dest"
        act cp "$PAYLOAD/cgh.conf" "$dest/cgh.conf"
    fi

    stubs=
    for hook in $(hook_names); do
        stub="$dest/$hook"
        if [ -e "$stub" ] && ! is_stub "$stub" && [ "$force" != 1 ]; then
            echo "WARNING: $dest_name/$hook exists and is not a cgh stub; skipped (use --force)" >&2
            continue
        fi
        write_stub "$stub"
        stubs="$stubs$hook
"
    done

    if [ "$dry" != 1 ]; then
        {
            echo "version=$VERSION"
            printf '%s\n' "$new_list"
            printf '%s' "$stubs"
        } | sed '/^$/d' >"$manifest"
    fi

    act git -C "$root" config --local core.hooksPath "$dest_name"

    # Old (v1/v2) installations keep their scripts in .git/hooks/<hook>.d,
    # which are not run any more now that core.hooksPath is set.
    common=$(cd "$root" && cd "$(git rev-parse --git-common-dir)" && pwd -P)
    for hook in "$common"/hooks/*; do
        [ -f "$hook" ] || continue
        grep -q 'CUSTOM-GIT-HOOK-SKELETON' "$hook" || continue
        echo "NOTE: $hook is from an older custom-git-hooks version; its ${hook##*/}.d/ scripts are no longer run."
        echo "      Move scripts you still need into $dest_name/hooks.d/${hook##*/}/ and delete the old ones."
    done

    cat <<EOF

Done. Next steps:
  * review $dest_name/cgh.conf (ticket format, protected branches, ...)
  * commit the $dest_name directory so that the whole team gets the same hooks:
      git add $dest_name && git commit
  * teammates enable it with:  sh install.sh   (or: git config core.hooksPath $dest_name)
EOF
}

if [ "$uninstall" = 1 ]; then
    do_uninstall
else
    do_install
fi
